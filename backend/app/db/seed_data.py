def _difficulty_for_stage(stage_id: int) -> int:
    if stage_id <= 5:
        return 1
    if stage_id <= 10:
        return 2
    return 3


def seed_if_empty(db: Session) -> None:
    if db.query(Stage).first() is not None:
        return

    for stage_item in STAGES:
        stage_id = stage_item["stage_id"]
        difficulty = _difficulty_for_stage(stage_id)
        db.add(
            Stage(
                stage_id=stage_id,
                title=stage_item["title"],
                description=stage_item["description"],
                difficulty=difficulty,
            )
        )
        for question_item in QUESTIONS[stage_id]:
            db.add(
                Question(
                    stage_id=stage_id,
                    question=question_item["question"],
                    choice1=question_item["choices"][0],
                    choice2=question_item["choices"][1],
                    choice3=question_item["choices"][2],
                    choice4=question_item["choices"][3],
                    answer=question_item["answer"],
                    explanation=question_item["explanation"],
                    difficulty=difficulty,
                    tag=question_item["tag"],
                )
            )

    db.commit()


def seed_default_user(db: Session) -> None:
    if db.query(User).filter(User.login_id == DEFAULT_USER_LOGIN_ID).first() is not None:
        return

    user = User(login_id=DEFAULT_USER_LOGIN_ID, password=hash_password(DEFAULT_USER_PASSWORD))
    db.add(user)
    db.commit()
