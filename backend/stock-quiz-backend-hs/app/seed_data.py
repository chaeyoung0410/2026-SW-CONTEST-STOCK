def seed():
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        if db.query(Stage).count() > 0:
            print("이미 데이터가 있어 건너뜁니다.")
            return

        for step_number, learning_content, questions in STAGES:
            db.add(Stage(step_number=step_number, learning_content=learning_content))
            db.flush()
            for question_text, answer in questions:
                db.add(Question(step_number=step_number, question_text=question_text, answer=answer))

        db.commit()
        print(f"{len(STAGES)}개 단계 데이터를 넣었습니다.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
